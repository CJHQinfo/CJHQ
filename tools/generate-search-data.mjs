#!/usr/bin/env node
/*
 * CJHQ - Borough Updates search data generator.
 * ------------------------------------------------------------------
 * The Borough Updates pages (local-updates/, fr/local-updates/) are standalone
 * and cannot load assets/site-core.js (it boots the whole SPA on parse). Their
 * header search therefore needs the same dataset the main site searches:
 * the static page index plus the resource categories.
 *
 * This extracts both literal arrays from assets/site-core.js - the single
 * source - and writes local-updates/search-data.js, a data-only script the
 * standalone pages load before their inline search code. Editing the arrays
 * inside site-core.js stays the only way the data changes.
 *
 * Run:  node tools/generate-search-data.mjs
 *       node tools/generate-search-data.mjs --check   (verify only, non-zero on drift)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'assets', 'site-core.js');
const OUT = join(ROOT, 'local-updates', 'search-data.js');

function extractArrayLiteral(src, decl){
  const start = src.indexOf(decl);
  if(start < 0) throw new Error('not found: ' + decl);
  let i = src.indexOf('[', start);
  let depth = 0, inStr = null, j = i;
  for(; j < src.length; j++){
    const ch = src[j];
    if(inStr){
      if(ch === '\\'){ j++; continue; }
      if(ch === inStr) inStr = null;
      continue;
    }
    if(ch === "'" || ch === '"' || ch === '`'){ inStr = ch; continue; }
    if(ch === '[') depth++;
    if(ch === ']'){ depth--; if(depth === 0) break; }
  }
  if(depth !== 0) throw new Error('unbalanced brackets for ' + decl);
  return src.slice(i, j + 1);
}

const src = readFileSync(SRC, 'utf8');
// eslint-disable-next-line no-eval -- our own repo literal, same trust as the source file
const pages = eval(extractArrayLiteral(src, 'const searchIndex = ['));
// eslint-disable-next-line no-eval
const cats = eval(extractArrayLiteral(src, 'const categories = ['));

// Mirror what the main site's handleSearch offers for a resource match: the
// category title with its item names as the body, page 'resources'.
const resources = cats.map(c => ({
  en: c.en, fr: c.fr,
  body_en: c.groups.flatMap(g => g.items.map(it => it.en)).join(', '),
  body_fr: c.groups.flatMap(g => g.items.map(it => it.fr)).join(', '),
}));

const banner = `/* GENERATED FILE - do not edit.
 * Source: assets/site-core.js (searchIndex + categories), regenerated by
 * tools/generate-search-data.mjs. Data for the Borough Updates header search;
 * the main site searches the same arrays inline. */
`;
const out = banner
  + 'window.CJHQ_SEARCH_PAGES = ' + JSON.stringify(pages, null, 1) + ';\n'
  + 'window.CJHQ_SEARCH_RESOURCES = ' + JSON.stringify(resources, null, 1) + ';\n';

if(process.argv.includes('--check')){
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if(cur !== out){ console.error('local-updates/search-data.js is out of date - run node tools/generate-search-data.mjs'); process.exit(1); }
  console.log('search-data.js is up to date.');
}else{
  writeFileSync(OUT, out);
  console.log('Wrote local-updates/search-data.js (' + pages.length + ' page entries, ' + resources.length + ' resources).');
}
