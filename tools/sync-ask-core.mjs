#!/usr/bin/env node
/*
 * CJHQ - shared Ask CJHQ core generator.
 * ------------------------------------------------------------------
 * Produces the two modules the external WhatsApp bridge imports:
 *
 *   ask-data.mjs   the 63-resource `categories` dataset
 *   ask-core.mjs   the deterministic engine: language detection, the seven
 *                  handlers in order, the halachic guard, resource matching,
 *                  answer shaping, and the askRun / askAnswer entry points
 *
 * DIRECTION OF TRUTH
 * index.html is the source; these modules are generated from it, the same way
 * the route files are. That is the opposite of extracting the logic out and
 * having the page import it back, and the reason is load order:
 *
 *   index.html calls renderAccordion() synchronously at top level, and that
 *   reads `categories`. A <script type="module"> is always deferred, so it
 *   cannot supply the dataset in time. Making the page import these modules
 *   would mean moving the whole boot tail behind the module - and if GitHub
 *   Pages serves .mjs with the wrong MIME type, a rejected module would leave
 *   the site blank. That risk is not worth taking for a community site whose
 *   pages carry border and emergency information.
 *
 * Generating in this direction gives the same guarantee that matters - there
 * is exactly one place the logic and the data are edited, and drift is
 * impossible because `--check` fails - without putting the public site behind
 * a runtime module load.
 *
 * USAGE
 *   node tools/sync-ask-core.mjs           regenerate both modules
 *   node tools/sync-ask-core.mjs --check   fail if they are out of date
 *
 * Run --check after every index.html change, next to
 * `node tools/generate-routes.mjs --check`.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const INDEX = join(ROOT, 'index.html');
const CHECK = process.argv.includes('--check');

const CORE_BEGIN = '/* ================= ASK CJHQ =================';
const CORE_END   = '/* ===== SHARED ASK CORE: END ========================================== */';
const AI_BEGIN   = '/* ===== BROWSER AI ADAPTER: BEGIN =====================================';
const AI_END     = '/* ===== BROWSER AI ADAPTER: END ======================================= */';

function slice(src, startMarker, endMarker, label) {
  const a = src.indexOf(startMarker);
  if (a < 0) throw new Error(`sync-ask-core: start marker missing for ${label}`);
  const b = src.indexOf(endMarker, a + startMarker.length);
  if (b < 0) throw new Error(`sync-ask-core: end marker missing for ${label}`);
  return { a, b: b + endMarker.length, text: src.slice(a, b + endMarker.length) };
}

const src = readFileSync(INDEX, 'utf8');

/* ---------------------------------------------------------------- data ---- */
const catStart = src.indexOf('\nconst categories = [');
const catEnd   = src.indexOf('\nconst contactCats', catStart);
if (catStart < 0 || catEnd < 0) throw new Error('sync-ask-core: categories block not found');
const categories = src.slice(catStart + 1, catEnd).trimEnd();

// Special Information / Yomim Tovim travel content. askSpecialInfo reads it,
// so the bridge needs it as much as the website does.
const siStart = src.indexOf('\nconst SPECIAL_INFO_COUNTRIES = [');
const siEnd   = src.indexOf('\nconst ', siStart + 10);
if (siStart < 0 || siEnd < 0) throw new Error('sync-ask-core: SPECIAL_INFO_COUNTRIES block not found');
const specialInfo = src.slice(siStart + 1, siEnd).trimEnd();

// The partner organizations CJHQ publishes. askOrganizations reads this, so
// the bridge needs the same list the marquee renders - not a second copy.
const pdStart = src.indexOf('\nlet PARTNERS_DATA = [');
const pdEnd   = src.indexOf('\n];', pdStart) + 3;
if (pdStart < 0 || pdEnd < 3) throw new Error('sync-ask-core: PARTNERS_DATA block not found');
const partners = src.slice(pdStart + 1, pdEnd).trimEnd().replace(/^let /, 'const ');

const dataOut = `/* GENERATED FILE - do not edit.
 * Source: index.html, regenerated by tools/sync-ask-core.mjs.
 * Edit the dataset in index.html and re-run the tool; editing this file
 * directly will be overwritten and will make --check fail.
 *
 * The 63 CJHQ resources. Imported by ask-core.mjs and, through it, by the
 * external WhatsApp bridge, so a resource added on the site reaches WhatsApp
 * without a second dataset being maintained anywhere.
 */
export ${categories}

export ${specialInfo}

export ${partners}
`;

/* ---------------------------------------------------------------- core ---- */
const core = slice(src, CORE_BEGIN, CORE_END, 'shared core');
const ai   = slice(core.text, AI_BEGIN, AI_END, 'browser AI adapter');

// Drop the browser-only span so the generated module carries no Firebase,
// gstatic or App Check reference at all.
let body = core.text.slice(0, ai.a) + core.text.slice(ai.b);

// cjhqNormalizeSearch lives outside the fenced region because the site's own
// search uses it too. The matcher needs it, so carry it across verbatim.
const nsStart = src.indexOf('function cjhqNormalizeSearch');
const nsEnd   = src.indexOf('\nconst searchIndex', nsStart);
if (nsStart < 0 || nsEnd < 0) throw new Error('sync-ask-core: cjhqNormalizeSearch not found');
const normalize = src.slice(nsStart, nsEnd).trimEnd();

const EXPORTS = [
  'askRun', 'askAnswer', 'askAnswerShape', 'askDetectLanguage', 'askDetectLocation',
  'askT', 'askBuildContext', 'askMatchResources', 'askBridgeTerms', 'askSortSources',
  'askPracticalHandlers', 'askHalachic', 'askEruv', 'askEmergency', 'askZmanim',
  'askCalendar', 'askCommunityDirectory', 'askCjhqResources', 'cjhqNormalizeSearch',
  'askOrganizations', 'askOrgRegistry', 'askSpecialInfo', 'askFindMtl',
  'ASK_TEMPLATES', 'askSmallTalk', 'ASK_FINDMTL'
];

const coreOut = `/* GENERATED FILE - do not edit.
 * Source: index.html, regenerated by tools/sync-ask-core.mjs.
 *
 * The shared Ask CJHQ deterministic engine. One implementation, two callers:
 * the CJHQ website runs this code inline, the external WhatsApp bridge imports
 * this module. There is no second copy of the handlers and no second language
 * detector.
 *
 * BROWSER-FREE BY CONSTRUCTION. The browser AI adapter is fenced off in
 * index.html and stripped here, so this module references no window, document,
 * Firebase, Firestore, App Check, gstatic import or browser storage. It is
 * stateless: no conversation history, no user identity, nothing that could
 * carry one caller's context into another's answer.
 *
 * HANDLER ORDER IS PART OF THE CONTRACT
 *   askHalachic -> askEruv -> askEmergency -> askZmanim -> askCalendar
 *   -> askCommunityDirectory -> askCjhqResources -> AI only where permitted
 * askHalachic runs first and stays authoritative: it calls the practical
 * handlers itself to attach what CJHQ actually knows beneath the referral to a
 * rov, so a caller cannot route around it.
 *
 * FOR THE BRIDGE
 *   import { askAnswer } from './ask-core.mjs';
 *   const res = await askAnswer({ text: incomingWhatsAppMessage });
 * Pass the raw message. Do not pre-translate or normalise it - askDetectLanguage
 * needs the original characters to tell Yiddish from Hebrew. Omit aiAdapter and
 * the deterministic path runs alone, which is what v1 wants.
 */
import { categories, SPECIAL_INFO_COUNTRIES, PARTNERS_DATA } from './ask-data.mjs';

${normalize}

${body}

export {
${EXPORTS.map(n => '  ' + n).join(',\n')}
};
export { categories, SPECIAL_INFO_COUNTRIES, PARTNERS_DATA };
`;

/* --------------------------------------------------------------- write ---- */
const targets = [
  { path: join(ROOT, 'ask-data.mjs'), text: dataOut, name: 'ask-data.mjs' },
  { path: join(ROOT, 'ask-core.mjs'), text: coreOut, name: 'ask-core.mjs' }
];

let drift = 0;
for (const t of targets) {
  const current = existsSync(t.path) ? readFileSync(t.path, 'utf8') : null;
  if (CHECK) {
    if (current !== t.text) { console.error(`DRIFT: ${t.name} is out of date`); drift++; }
    else console.log(`ok: ${t.name}`);
  } else {
    writeFileSync(t.path, t.text);
    console.log(`written: ${t.name} (${t.text.length} chars)`);
  }
}

if (CHECK && drift) {
  console.error(`\n${drift} module(s) out of date. Run: node tools/sync-ask-core.mjs`);
  process.exit(1);
}
if (CHECK) console.log('\nshared Ask CJHQ core is in sync with index.html.');
